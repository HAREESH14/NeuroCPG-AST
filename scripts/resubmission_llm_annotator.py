"""
LLM-Assisted Annotation for NeuroAST Precision Audit.

Uses Gemini Pro (via litellm) to annotate hallucination samples
as TRUE_POSITIVE (Y/N), provide SUB_CATEGORY for Invented, and
write structured reasoning.

Approach:
  - Annotator A: Gemini Pro with detailed code-review prompt
  - Annotator B: Gemini Pro with a rephrased prompt (for Cohen's κ)
  - Human: YOU manually review disagreements and spot-check

Usage:
    # Annotator A (primary)
    uv run python scripts/resubmission_llm_annotator.py \
        --input results/resubmission/audit_annotator_A.csv \
        --output results/resubmission/audit_annotator_A_filled.csv \
        --annotator A

    # Annotator B (independent, rephrased prompt)
    uv run python scripts/resubmission_llm_annotator.py \
        --input results/resubmission/audit_annotator_B.csv \
        --output results/resubmission/audit_annotator_B_filled.csv \
        --annotator B

    # Then compute statistics:
    uv run python scripts/resubmission_compute_audit_stats.py \
        --annotator-a results/resubmission/audit_annotator_A_filled.csv \
        --annotator-b results/resubmission/audit_annotator_B_filled.csv
"""

from __future__ import annotations

import argparse
import csv
import json
import logging
import os
import re
import time
from pathlib import Path

import litellm

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
)
logger = logging.getLogger(__name__)

# ── Configuration ──────────────────────────────────────────────────────────
DEFAULT_MODEL = "meta/llama-3.3-70b-instruct"

# Default NVIDIA NIM endpoint (override via --nvidia-url or NVIDIA_API_BASE).
DEFAULT_NVIDIA_URL = "https://integrate.api.nvidia.com/v1"

# Resolve NVIDIA API key once at import time so litellm picks it up.
_NVIDIA_API_KEY = os.environ.get("NVIDIA_API_KEY") or os.environ.get("NVIDIA_NIM_API_KEY")
if _NVIDIA_API_KEY:
    os.environ["NVIDIA_API_KEY"] = _NVIDIA_API_KEY
NVIDIA_API_BASE = os.environ.get("NVIDIA_API_BASE", DEFAULT_NVIDIA_URL)

# ── Prompts ────────────────────────────────────────────────────────────────

SYSTEM_PROMPT = """You are an expert static analysis researcher performing a precision audit
of a code translation verification tool called NeuroAST.

NeuroAST verifies LLM-generated C-to-Java translations by comparing the
Abstract Syntax Trees (AST) and Code Property Graphs (CPG) of the source
C program and the target Java program. It flags structural and semantic
"hallucinations" — places where the Java translation deviates from the
C source in ways that could indicate an error.

YOUR TASK: For each flagged hallucination, determine if NeuroAST's flag
is a TRUE POSITIVE (the Java code genuinely deviates from C in a way that
constitutes an error or structural mismatch) or a FALSE POSITIVE (the
Java code is actually a valid, correct translation despite looking different).

IMPORTANT RULES:
1. VALID cross-language differences are NOT hallucinations:
   - C uses malloc/free → Java uses new (no free needed) — this is VALID
   - C uses printf → Java uses System.out.println — this is VALID
   - C has no class → Java wraps in a class — this is VALID
   - C uses pointers → Java uses array indices — this is VALID
   - C has header includes → Java has imports — this is VALID

2. These ARE genuine hallucinations (TRUE POSITIVE):
   - Java adds a try-catch block where C has no error handling → INVENTED
   - Java is missing a for-loop that exists in C → MISSING
   - Java nests a statement deeper than C does → DEPTH_MISMATCH
   - Java breaks a variable's def-use chain → LOST_CONTROL_DEP
   - Java changes int to float inappropriately → INVALID_TYPE_TRANSFORM

3. For the "invented" category, also identify WHAT was invented:
   - try_catch: An invented try-catch or exception handling block
   - helper_variable: An unnecessary helper/temp variable
   - extra_branch: An invented if/else that doesn't exist in C
   - extra_loop: An invented for/while loop
   - wrapper_structure: An unnecessary wrapper class or method
   - extra_function_call: Calling methods that have no equivalent in C
   - extra_return: Adding return statements that don't exist in C
   - other: Anything else that was invented
"""

ANNOTATOR_A_PROMPT = """Analyze this flagged hallucination from NeuroAST.

**Category flagged by NeuroAST:** {category}
**Confidence score:** {confidence}
**Source file:** {source_file}
**Model that generated the translation:** {model}

### C Source Code (Original):
```c
{c_source}
```

### Java Translation (Generated by LLM):
```java
{java_translation}
```

### Your Analysis:

Compare the C source and Java translation carefully. NeuroAST flagged this
as a "{category}" hallucination.

Respond with ONLY a valid JSON object (no markdown fences, no extra text):
{{
    "true_positive": "Y" or "N",
    "sub_category": "<only if category is 'invented': try_catch|helper_variable|extra_branch|extra_loop|wrapper_structure|extra_function_call|extra_return|other, otherwise empty string>",
    "reasoning": "<2-3 sentences explaining your judgment. Be specific about which construct is the issue.>"
}}"""

ANNOTATOR_B_PROMPT = """You are reviewing a code translation verification result.

A tool compared a C program with its LLM-generated Java translation and
flagged a potential issue categorized as: **{category}**

**File:** {source_file} | **Translator model:** {model} | **Tool confidence:** {confidence}

--- ORIGINAL C PROGRAM ---
```c
{c_source}
```

--- LLM JAVA TRANSLATION ---
```java
{java_translation}
```

QUESTION: Is this flag correct? Does the Java translation genuinely have
a "{category}" problem compared to the C source?

Remember:
- Normal C-to-Java differences (malloc→new, printf→println, class wrapping) are NOT errors
- But added try-catch, missing loops, wrong nesting, broken variables ARE errors

Reply with ONLY a JSON object:
{{
    "true_positive": "Y" or "N",
    "sub_category": "<for 'invented' flags only: try_catch|helper_variable|extra_branch|extra_loop|wrapper_structure|extra_function_call|extra_return|other, else empty>",
    "reasoning": "<2-3 sentences explaining why this is or isn't a real issue.>"
}}"""


def _extract_json(raw: str) -> dict:
    """Robustly extract JSON from LLM output."""
    # Strip markdown fences if present
    raw = raw.strip()
    raw = re.sub(r"^```(?:json)?\s*", "", raw)
    raw = re.sub(r"\s*```$", "", raw)

    try:
        return json.loads(raw)
    except json.JSONDecodeError:
        pass

    # Try to find first {...} block
    match = re.search(r"\{.*\}", raw, re.DOTALL)
    if match:
        try:
            return json.loads(match.group(0))
        except json.JSONDecodeError:
            pass

    return {"_parse_failed": True, "_raw": raw[:300]}


def annotate_single(
    row: dict[str, str],
    annotator: str,
    model: str,
    url: str = DEFAULT_NVIDIA_URL,
) -> dict[str, str]:
    """
    Send one hallucination instance to an LLM judge for annotation.

    Defaults to the NVIDIA NIM endpoint at ``https://integrate.api.nvidia.com/v1``.
    If ``model`` is the raw NVIDIA model id (e.g. ``meta/llama-3.3-70b-instruct``),
    we route via litellm's ``nvidia_nim/`` provider and attach the API key from
    ``NVIDIA_API_KEY`` (or ``NVIDIA_NIM_API_KEY``).
    """
    prompt_template = ANNOTATOR_A_PROMPT if annotator == "A" else ANNOTATOR_B_PROMPT

    prompt = prompt_template.format(
        category=row["category"],
        confidence=row["confidence"],
        source_file=row["source_file"],
        model=row["model"],
        c_source=row["c_source_snippet"],
        java_translation=row["java_translation_snippet"],
    )

    try:
        completion_kwargs: dict = {
            "model": model,
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": prompt},
            ],
            "timeout": 120,
            "temperature": 0.1,  # Low temperature for consistency
        }

        # Route NVIDIA NIM calls correctly. litellm expects ``api_base`` (not
        # ``url``) for custom OpenAI-compatible endpoints and an explicit
        # ``api_key`` for authenticated hosts.
        is_nvidia_model = (
            model.startswith("nvidia_nim/")
            or model.startswith("nvidia/")
            or model == "meta/llama-3.3-70b-instruct"
            or "nvidia" in (url or "")
        )
        if is_nvidia_model:
            completion_kwargs["api_base"] = url or NVIDIA_API_BASE
            nvidia_key = (
                os.environ.get("NVIDIA_API_KEY")
                or os.environ.get("NVIDIA_NIM_API_KEY")
            )
            if nvidia_key:
                completion_kwargs["api_key"] = nvidia_key
            # If the user supplied the raw NVIDIA model id without a provider
            # prefix, attach the ``nvidia_nim/`` prefix so litellm routes it.
            if model == "meta/llama-3.3-70b-instruct":
                completion_kwargs["model"] = f"nvidia_nim/{model}"

        response = litellm.completion(**completion_kwargs)

        raw = response.choices[0].message.content or ""
        parsed = _extract_json(raw)

        if parsed.get("_parse_failed"):
            logger.warning("Parse failed for row %s: %s", row["id"], parsed.get("_raw", ""))
            return {
                "TRUE_POSITIVE": "PARSE_ERROR",
                "SUB_CATEGORY": "",
                "NOTES": f"PARSE_ERROR: {raw[:200]}",
            }

        tp = str(parsed.get("true_positive", "")).strip().upper()
        if tp not in ("Y", "N"):
            tp = "Y" if tp in ("YES", "TRUE", "1") else "N"

        sub_cat = str(parsed.get("sub_category", "")).strip().lower()
        reasoning = str(parsed.get("reasoning", ""))

        return {
            "TRUE_POSITIVE": tp,
            "SUB_CATEGORY": sub_cat if row["category"] == "invented" else "",
            "NOTES": reasoning,
        }

    except Exception as e:
        logger.error("API error for row %s: %s", row["id"], e)
        return {
            "TRUE_POSITIVE": "API_ERROR",
            "SUB_CATEGORY": "",
            "NOTES": f"API_ERROR: {e}",
        }


def run_annotation(
    input_csv: Path,
    output_csv: Path,
    annotator: str,
    model: str,
    resume: bool = True,
    limit: int | None = None,
    batch_delay: float = 1.0,
) -> None:
    """Run LLM annotation on all rows."""

    # Load input
    with input_csv.open() as f:
        reader = csv.DictReader(f)
        rows = list(reader)

    logger.info("Loaded %d rows from %s", len(rows), input_csv)

    if limit:
        rows = rows[:limit]
        logger.info("Limiting to first %d rows", limit)

    # Resume: load existing output if present
    already_done: dict[str, dict[str, str]] = {}
    if resume and output_csv.exists():
        with output_csv.open() as f:
            existing = list(csv.DictReader(f))
            for r in existing:
                if r.get("TRUE_POSITIVE", "").strip() and r["TRUE_POSITIVE"] not in ("", "PARSE_ERROR", "API_ERROR"):
                    already_done[r["id"]] = r
        logger.info("Resuming: %d rows already annotated", len(already_done))

    # Process
    results: list[dict[str, str]] = []
    success = 0
    errors = 0

    for i, row in enumerate(rows):
        row_id = row["id"]

        # Skip if already done
        if row_id in already_done:
            # Preserve existing annotation
            merged = dict(row)
            merged.update({
                "TRUE_POSITIVE": already_done[row_id]["TRUE_POSITIVE"],
                "SUB_CATEGORY": already_done[row_id].get("SUB_CATEGORY", ""),
                "NOTES": already_done[row_id].get("NOTES", ""),
            })
            results.append(merged)
            continue

        logger.info(
            "[%d/%d] Annotating row %s: %s / %s / %s",
            i + 1, len(rows), row_id, row["model"], row["source_file"], row["category"],
        )

        annotation = annotate_single(row, annotator, model,url)

        merged = dict(row)
        merged.update(annotation)
        results.append(merged)

        if annotation["TRUE_POSITIVE"] in ("Y", "N"):
            success += 1
            logger.info(
                "  → %s (sub=%s) — %s",
                annotation["TRUE_POSITIVE"],
                annotation["SUB_CATEGORY"],
                annotation["NOTES"][:100],
            )
        else:
            errors += 1
            logger.warning("  → ERROR: %s", annotation["TRUE_POSITIVE"])

        # Save incrementally every 10 rows
        if (i + 1) % 10 == 0:
            _save_csv(results, output_csv, rows[0].keys())
            logger.info("  [checkpoint] Saved %d rows", len(results))

        # Rate limiting
        time.sleep(batch_delay)

    # Final save
    _save_csv(results, output_csv, rows[0].keys())

    # Summary
    annotated = [r for r in results if r["TRUE_POSITIVE"] in ("Y", "N")]
    tp_count = sum(1 for r in annotated if r["TRUE_POSITIVE"] == "Y")
    fp_count = sum(1 for r in annotated if r["TRUE_POSITIVE"] == "N")

    logger.info("=" * 60)
    logger.info("ANNOTATION COMPLETE — Annotator %s", annotator)
    logger.info("=" * 60)
    logger.info("Total rows:       %d", len(results))
    logger.info("Successfully annotated: %d", len(annotated))
    logger.info("  True Positives:  %d (%.1f%%)", tp_count, 100 * tp_count / len(annotated) if annotated else 0)
    logger.info("  False Positives: %d (%.1f%%)", fp_count, 100 * fp_count / len(annotated) if annotated else 0)
    logger.info("Errors:           %d", errors)
    logger.info("Output:           %s", output_csv)

    # Per-category breakdown
    by_cat: dict[str, dict[str, int]] = {}
    for r in annotated:
        cat = r["category"]
        if cat not in by_cat:
            by_cat[cat] = {"Y": 0, "N": 0}
        by_cat[cat][r["TRUE_POSITIVE"]] += 1

    logger.info("\nPer-category precision:")
    for cat, counts in sorted(by_cat.items()):
        total = counts["Y"] + counts["N"]
        precision = counts["Y"] / total if total > 0 else 0
        logger.info("  %-25s %3d/%3d = %.1f%%", cat, counts["Y"], total, precision * 100)

    # Sub-category breakdown for invented
    if any(r["SUB_CATEGORY"] for r in annotated):
        logger.info("\nInvented sub-categories:")
        sub_counts: dict[str, int] = {}
        for r in annotated:
            if r.get("SUB_CATEGORY"):
                sub = r["SUB_CATEGORY"]
                sub_counts[sub] = sub_counts.get(sub, 0) + 1
        for sub, count in sorted(sub_counts.items(), key=lambda x: -x[1]):
            logger.info("  %-20s %d", sub, count)


def _save_csv(
    rows: list[dict[str, str]],
    output_csv: Path,
    fieldnames,
) -> None:
    """Save annotated rows to CSV."""
    output_csv.parent.mkdir(parents=True, exist_ok=True)

    all_fields = list(fieldnames)
    for extra in ["TRUE_POSITIVE", "SUB_CATEGORY", "NOTES"]:
        if extra not in all_fields:
            all_fields.append(extra)

    with output_csv.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=all_fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="LLM-assisted annotation for precision audit"
    )
    parser.add_argument(
        "--input", type=Path, required=True,
        help="Input CSV (from resubmission_stratified_sample.py)",
    )
    parser.add_argument(
        "--output", type=Path, required=True,
        help="Output CSV with annotations filled in",
    )
    parser.add_argument(
        "--annotator", type=str, choices=["A", "B"], default="A",
        help="Annotator identity (A or B — uses different prompts for Cohen's κ)",
    )
    parser.add_argument(
        "--model", type=str, default=DEFAULT_MODEL,
        help=f"LLM model to use (default: {DEFAULT_MODEL})",
    )
    parser.add_argument(
        "--limit", type=int, default=None,
        help="Only annotate first N rows (for testing)",
    )
    parser.add_argument(
        "--resume", action="store_true", default=True,
        help="Resume from previous partial run (default: True)",
    )
    parser.add_argument(
        "--no-resume", action="store_false", dest="resume",
        help="Start fresh, overwriting any existing output",
    )
    parser.add_argument(
        "--delay", type=float, default=1.0,
        help="Delay between API calls in seconds (default: 1.0)",
    )
    args = parser.parse_args()

    logger.info("Model:     %s", args.model)
    logger.info("Annotator: %s (uses %s prompt)", args.annotator,
                "detailed code-review" if args.annotator == "A" else "independent rephrased")
    logger.info("Input:     %s", args.input)
    logger.info("Output:    %s", args.output)

    run_annotation(
        input_csv=args.input,
        output_csv=args.output,
        annotator=args.annotator,
        model=args.model,
        resume=args.resume,
        limit=args.limit,
        batch_delay=args.delay,
    )

    logger.info("✅ Annotation complete!")
    logger.info("Next steps:")
    logger.info("  1. Run the OTHER annotator (A or B) with the same script")
    logger.info("  2. Manually review any PARSE_ERROR or API_ERROR rows")
    logger.info("  3. Run: uv run python scripts/resubmission_compute_audit_stats.py \\")
    logger.info("       --annotator-a <A_filled.csv> --annotator-b <B_filled.csv>")


if __name__ == "__main__":
    main()
